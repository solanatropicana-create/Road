const KEY = 'underfoot.lang';

function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'tr') return saved;
  } catch {
    // storage unavailable
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

let lang: Lang = detect();

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang): void {
  lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    // not remembered; fine
  }
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}

if (typeof document !== 'undefined') document.documentElement.lang = lang;

export type Vars = Record<string, string | number>;

/** The text for `key` in the current language, with `{name}` filled from `vars`. */
export function t(key: string, vars?: Vars): string {
  const table = lang === 'tr' ? TR : EN;
  let s = (table as Record<string, string>)[key] ?? (EN as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** A decimal in the current language's style (Turkish uses a comma). */
export function num(v: number, digits = 1): string {
  const s = v.toFixed(digits);
  return lang === 'tr' ? s.replace('.', ',') : s;
}
